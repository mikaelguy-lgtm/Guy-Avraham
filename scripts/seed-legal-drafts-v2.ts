async function upsertDraft(store: PostgresStore, documentType: "TERMS" | "PRIVACY" | "DPA", title: string, content: string, adminId: number) {
  const active = await store.getActiveLegalDocumentVersion(documentType);
  const existingDraft = await store.getDraftLegalDocumentVersion(documentType);
  if (existingDraft) {
    console.log(`${documentType}: a DRAFT already exists (id ${existingDraft.id}, v${existingDraft.versionNumber}) — updating its content instead of creating a new one.`);
    await store.updateLegalDocumentDraft(existingDraft.id, {
      title, content, contactEmail: "support@syncash.co.il", contactPhone: null, contactAddress: null,
      effectiveDate: existingDraft.effectiveDate
    });
    console.log(`${documentType}: updated draft v${existingDraft.versionNumber} (id ${existingDraft.id}).`);
    return;
  }
  const draft = await store.createLegalDocumentDraft(documentType, adminId);
  await store.updateLegalDocumentDraft(draft.id, {
    title, content, contactEmail: "support@syncash.co.il", contactPhone: null, contactAddress: null,
    effectiveDate: null
  });
  console.log(`${documentType}: created draft v${draft.versionNumber} (id ${draft.id})${active ? ` — active published version is v${active.versionNumber}` : " — no active published version yet"}. Left UNPUBLISHED for SUPER_ADMIN review.`);
}

